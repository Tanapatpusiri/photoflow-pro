import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile('lib/football-gallery-retention.js','utf8');
const {addRetentionMonths,oneYearAfterEvent,validRetentionDate}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(oneYearAfterEvent('2026-11-14'),'2027-11-14');
assert.equal(oneYearAfterEvent('2024-02-29T00:00:00.000Z'),'2025-02-28');
assert.equal(oneYearAfterEvent('2025-02-30'),'');
assert.equal(oneYearAfterEvent(null),'');
assert.equal(validRetentionDate('2026-11-14','2027-11-14','2026-11-15'),true);
assert.equal(validRetentionDate('2026-11-14','2027-11-15','2026-11-15'),false);
assert.equal(validRetentionDate('2026-11-14','2026-11-15','2026-11-15'),false);
assert.equal(validRetentionDate(null,'2027-11-14','2026-11-15'),false);
assert.equal(validRetentionDate('2026-11-14','2027-02-30','2026-11-15'),false);
assert.equal(addRetentionMonths('2024-01-31',1),'2024-02-29');
assert.equal(addRetentionMonths('2025-01-31',1),'2025-02-28');
assert.equal(addRetentionMonths('2026-11-14',6),'2027-05-14');
assert.equal(addRetentionMonths('2026-11-14',13),'');
assert.equal(validRetentionDate('2026-11-14','2027-05-14','2026-11-15',6),true);
assert.equal(validRetentionDate('2026-11-14','2027-05-15','2026-11-15',6),false);
assert.equal(validRetentionDate('2026-11-14','2026-11-13','2026-11-01',6),false);
console.log('PASS: calendar year, leap day, invalid and missing event dates');
